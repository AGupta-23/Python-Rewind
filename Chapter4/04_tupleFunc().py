numbers = (1, 2, 3, 2, 4, 2)

# Count
print(numbers.count(2))     # 3

# Index
print(numbers.index(3))     # 2

# Length
print(len(numbers))         # 6

# Maximum Value
print(max(numbers))         # 4

# Minimum Value
print(min(numbers))         # 1

# Sum
print(sum(numbers))         # 14

# Convert Tuple to List
newList = list(numbers)
print(newList)              # [1, 2, 3, 2, 4, 2]

# Convert List to Tuple
data = [10, 20, 30]

newTuple = tuple(data)
print(newTuple)             # (10, 20, 30)